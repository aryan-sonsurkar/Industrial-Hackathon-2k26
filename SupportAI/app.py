    if escalation_level == "high":
        priority_score += 50
    elif escalation_level == "medium":
        priority_score += 30
    else:
        priority_score += 10
    
    # Sentiment factor
    if sentiment == "Angry":
        priority_score += 25
    elif sentiment == "Neutral":
        priority_score += 10
    
    # Repetition factor
